export function getIntlLocale(locale: BankLocale): string {
  return LOCALE_TO_INTL[locale]
}

export function translate(locale: BankLocale, key: TranslationKey): string {
  const dictionary = translations[locale]
  return (dictionary as Partial<Record<TranslationKey, string>>)[key] ?? translations.en[key]
}

export function useI18n() {
  const locale = useBankSession((s) => s.locale)
  const currency = useBankSession((s) => s.currency)
  return useMemo(() => {
    const intlLocale = getIntlLocale(locale)
    return {
      locale,
      currency,
      intlLocale,
      t: (key: TranslationKey) => translate(locale, key),
      money: (value: number, options?: Intl.NumberFormatOptions) => formatMoney(value, currency, intlLocale, options),
      signedMoney: (value: number, options?: Intl.NumberFormatOptions) => formatSignedMoney(value, currency, intlLocale, options),
      number: (value: number, options?: Intl.NumberFormatOptions) => new Intl.NumberFormat(intlLocale, options).format(value),
      relativeTime: (timestamp: number) => formatLocalizedRelativeTime(timestamp, intlLocale),
      dateTime: (timestamp: number, options?: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(intlLocale, options).format(new Date(timestamp)),
      currencySymbol: CURRENCY_SYMBOLS[currency],
    }
  }, [currency, locale])
}

export function formatMoney(value: number, currency: BankCurrency = 'USD', locale = 'en-US', options: Intl.NumberFormatOptions = {}): string {
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency,
    maximumFractionDigits: 2,
    minimumFractionDigits: 2,
    ...options,
  }).format(value)
}

export function formatSignedMoney(value: number, currency: BankCurrency = 'USD', locale = 'en-US', options: Intl.NumberFormatOptions = {}): string {
  const sign = value < 0 ? '−' : '+'
  return `${sign}${formatMoney(Math.abs(value), currency, locale, options)}`
}

export function formatLocalizedRelativeTime(timestamp: number, locale = 'en-US'): string {
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: 'auto', style: 'short' })
  const elapsedSec = Math.round((timestamp - Date.now()) / 1000)
  const ranges: Array<[Intl.RelativeTimeFormatUnit, number]> = [
    ['year', 3600 * 24 * 365],
    ['month', 3600 * 24 * 30],
    ['week', 3600 * 24 * 7],
    ['day', 3600 * 24],
    ['hour', 3600],
    ['minute', 60],
    ['second', 1],
  ]
  for (const [unit, seconds] of ranges) {
    if (Math.abs(elapsedSec) >= seconds || unit === 'second') {
      return rtf.format(Math.round(elapsedSec / seconds), unit)
    }
  }
  return rtf.format(elapsedSec, 'second')
}
